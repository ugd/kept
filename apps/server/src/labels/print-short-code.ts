/** Build a whole-dot SVG path with no dependency on fonts in the operating system. */
export function drawShortCode(code: string, scale: number, left: number, top: number): string {
  let path = '';
  for (const [index, character] of [...code].entries()) {
    const rows = glyphs[character];
    if (!rows) throw new Error('Unknown character in label code');
    for (const [y, row] of rows.split(' ').entries()) {
      for (const [x, pixel] of [...row].entries()) {
        if (pixel !== '1') continue;
        const startX = left + (index * 6 + x) * scale;
        const startY = top + y * scale;
        path += `M${startX} ${startY}h${scale}v${scale}h-${scale}z`;
      }
    }
  }
  return path;
}
